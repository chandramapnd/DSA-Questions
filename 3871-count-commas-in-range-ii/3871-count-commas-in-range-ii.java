class Solution {
    public long countCommas(long n) {
        long res = 0;
        if(n == 1000000000000000L){
            res += 5;
            n = 999999999999999L;
        }

        if(n <= 999999999999999L && n >= 1000000000000L){
            res += (n - 1000000000000L + 1) * 4;
            n = 999999999999L;
        }

        if(n <= 999999999999L && n >= 1000000000L){
            res += (n - 1000000000L + 1) * 3;
            n = 999999999L;
        }

        if(n <= 999999999L && n >= 1000000L){
            res += (n - 1000000L + 1) * 2;
            n = 999999L;
        }

        if(n <= 999999L && n >= 1000L){
            res += (n - 1000L + 1) ;
        }
        return res;
    }
}